"""Render docs/cost-summary.md from the LLM call log (JSONL).

    python scripts/generate_cost_summary.py --log var/logs/llm_calls.jsonl --out docs/cost-summary.md
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import OrderedDict, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from review_assistant.config import MODEL_PRICING_USD_PER_1M, PRICING_ACCESS_DATE, PRICING_SOURCE  # noqa: E402
from review_assistant.llm.calllog import read_jsonl  # noqa: E402

LABEL_DESCRIPTIONS = {
    "canonical-live": "Pass 1: all 10 cases through the API, live Gemini, cold cache",
    "cache-demo": "Pass 2: all 10 cases again with the cache enabled (shows cache hits)",
    "eval-live": "Evaluation run (eval/run_eval.py) through the API, live, cache disabled",
    "stability": "Stability check: LLM-dependent cases repeated with cache disabled",
    "eval-mock-compare": "Mock client on the same prompts, for mock-vs-live agreement (no provider call, USD 0, estimated tokens)",
    "ui": "Reviewer UI: 'Review all cases' clicked with Live Gemini and the cache switched off",
}


def _case_ids() -> list[str]:
    with (ROOT / "data" / "case_manifest.csv").open(newline="") as fh:
        return sorted({r["case_id"] for r in csv.DictReader(fh)})


def render(rows: list[dict]) -> str:
    out: list[str] = []
    w = out.append
    providers = sorted({r["provider"] for r in rows})
    models = sorted({r["model"] for r in rows if r["provider"] != "mock"})
    w("# LLM Usage and Cost Summary\n")
    w("> Generated by `scripts/generate_cost_summary.py` from the per-call log `var/logs/llm_calls.jsonl` "
      "(snapshot committed as `docs/evidence/llm_calls.jsonl`). Do not edit by hand.\n")
    w("## Pricing Assumptions\n")
    w(f"- Provider pricing source and access date: Google Gemini Developer API pricing, <{PRICING_SOURCE}>, accessed {PRICING_ACCESS_DATE} (Standard tier, paid).")
    for m in models or ["gemini-3.1-flash-lite"]:
        p = MODEL_PRICING_USD_PER_1M.get(m)
        if p:
            w(f"- `{m}` input price: USD {p['input']:.2f} per 1M tokens (text).")
            w(f"- `{m}` output price: USD {p['output']:.2f} per 1M tokens, including thinking tokens.")
    w("- Cached-input price: N/A. Provider context caching is not used; the application's own response cache "
      "serves repeat prompts locally, so a cache hit makes no provider call and costs USD 0.")
    w("- Calculation formula and rounding rule: `cost = input_tokens / 1,000,000 x input_price + "
      "(output_tokens + thinking_tokens) / 1,000,000 x output_price`, rounded to 6 decimal places per call. "
      "Totals are sums of the rounded per-call values.")
    w("- Token source: `usage_metadata` returned by the Gemini API (`prompt_token_count`, `candidates_token_count`, "
      "`thoughts_token_count`). Mock rows (if any) use a chars/4 estimate and are costed at USD 0.")
    w("- Retries: tokens are summed across attempts that returned a response. An attempt that timed out returns no "
      "usage data, so it is counted in `Retries` and `Latency` but contributes 0 tokens here; the provider may still "
      "bill it. Latency is wall-clock time for the whole logical call, including failed attempts and backoff.")
    w(f"- Providers in this log: {', '.join(providers) or 'none'}.\n")

    w("## What Triggers an LLM Call\n")
    w("Only the SOP-03 diagnosis-consistency step calls the LLM, at most once per review. It is skipped "
      "deterministically when the claim diagnosis is blank (already a SOP-01 finding) or when the claim and "
      "discharge diagnoses match exactly with no uncertainty wording. In the supplied data that means CASE-001, "
      "CASE-003, CASE-007 and CASE-008 make no LLM call, and the other six cases make one call each.\n")

    groups: "OrderedDict[str, list[dict]]" = OrderedDict()
    for r in rows:
        groups.setdefault(r.get("run_label", "adhoc"), []).append(r)

    w("## Per-Call Log\n")
    for label, items in groups.items():
        w(f"### Run label `{label}`\n")
        if label in LABEL_DESCRIPTIONS:
            w(LABEL_DESCRIPTIONS[label] + ".\n")
        w("| # | Timestamp (UTC) | Case ID | Call / Step | Provider | Model | Input Tokens | Output Tokens | Estimated Cost (USD) | Latency (ms) | Retries | Cache Status | Status |")
        w("|---:|---|---|---|---|---|---:|---:|---:|---:|---:|---|---|")
        for i, r in enumerate(items, start=1):
            w(f"| {i} | {r['timestamp'][:19]} | {r['case_id']} | {r['step']} | {r['provider']} | {r['model']} | "
              f"{r['input_tokens']} | {r['output_tokens']} | {r['cost_usd']:.6f} | {r['latency_ms']} | "
              f"{r['retries']} | {r['cache_status']} | {r['status']} |")
        w("")

    mock_rows = [r for r in rows if r["provider"] == "mock"]
    rows = [r for r in rows if r["provider"] != "mock"]
    w("## Totals by Case\n")
    w("All live-provider runs in the log combined (cache hits included at USD 0). Cases with 0 calls were fully "
      "decided by deterministic rules."
      + (f" The {len(mock_rows)} mock rows above use estimated tokens and cost USD 0; they are excluded from "
         "the totals below so token counts reflect real Gemini usage only." if mock_rows else "") + "\n")
    w("| Case ID | LLM Calls | Provider Calls (cache miss/disabled) | Cache Hits | Input Tokens | Output Tokens | Estimated Cost (USD) | Total Latency (ms) |")
    w("|---|---:|---:|---:|---:|---:|---:|---:|")
    by_case: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by_case[r["case_id"]].append(r)
    for case_id in _case_ids():
        items = by_case.get(case_id, [])
        hits = sum(1 for r in items if r["cache_status"] == "hit")
        w(f"| {case_id} | {len(items)} | {len(items) - hits} | {hits} | {sum(r['input_tokens'] for r in items)} | "
          f"{sum(r['output_tokens'] for r in items)} | {sum(r['cost_usd'] for r in items):.6f} | "
          f"{sum(r['latency_ms'] for r in items)} |")
    w("")

    w("## Totals by Run Label\n")
    w("| Run Label | LLM Calls | Input Tokens | Output Tokens | Estimated Cost (USD) | Mean Latency, provider calls (ms) |")
    w("|---|---:|---:|---:|---:|---:|")
    for label, items in groups.items():
        items = [r for r in items if r["provider"] != "mock"]
        if not items:
            continue
        live = [r for r in items if r["cache_status"] != "hit"]
        mean = int(sum(r["latency_ms"] for r in live) / len(live)) if live else 0
        w(f"| {label} | {len(items)} | {sum(r['input_tokens'] for r in items)} | {sum(r['output_tokens'] for r in items)} | "
          f"{sum(r['cost_usd'] for r in items):.6f} | {mean} |")
    w("")

    w("## Overall Total\n")
    w("| LLM Calls | Input Tokens | Output Tokens | Estimated Cost (USD) |")
    w("|---:|---:|---:|---:|")
    w(f"| {len(rows)} | {sum(r['input_tokens'] for r in rows)} | {sum(r['output_tokens'] for r in rows)} | "
      f"{sum(r['cost_usd'] for r in rows):.6f} |")
    w("")
    one_pass = groups.get("canonical-live", [])
    if one_pass:
        cost = sum(r["cost_usd"] for r in one_pass)
        w("## Unit Economics\n")
        w(f"- One full pass over the 10 supplied cases (`canonical-live`): {len(one_pass)} LLM calls, "
          f"USD {cost:.6f}, i.e. about USD {cost / 10:.6f} per case.")
        w(f"- Projected at 10,000 cases/month with the same mix: about USD {cost / 10 * 10000:.2f}/month in LLM spend "
          "(before cache hits).")
        w("- The main cost driver is the fixed system prompt (SOP-03 and SOP-06 text plus instructions, about 700 "
          "tokens). Provider-side context caching or batch pricing would cut it further.\n")
    w("No API keys or document text are stored in the log; it holds token counts, cost, latency, retries, cache "
      "status, and a SHA-256 of the request.")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--log", default=str(ROOT / "var" / "logs" / "llm_calls.jsonl"))
    parser.add_argument("--out", default=str(ROOT / "docs" / "cost-summary.md"))
    args = parser.parse_args()
    rows = read_jsonl(Path(args.log))
    Path(args.out).write_text(render(rows), encoding="utf-8")
    print(f"Wrote {args.out} from {len(rows)} call record(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
